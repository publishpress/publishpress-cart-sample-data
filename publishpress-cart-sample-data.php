defined('ABSPATH') || exit;

final class PPCart_Sample_Data_Plugin
{
    const META_KEY = '_ppcart_sample_data';

    public function __construct()
    {
        add_action('admin_menu', array($this, 'register_page'));
        add_action('admin_post_ppcart_sample_data_generate', array($this, 'generate'));
        add_action('admin_post_ppcart_sample_data_remove', array($this, 'remove'));
    }

    public function register_page()
    {
        add_submenu_page('ppcart', __('Sample Data', 'publishpress-cart-sample-data'), __('Sample Data', 'publishpress-cart-sample-data'), 'manage_options', 'ppcart-sample-data', array($this, 'render'));
    }

    public function render()
    {
        $ready = $this->cart_is_available();
        ?>
        <div class="wrap"><h1><?php esc_html_e('PublishPress Cart Sample Data', 'publishpress-cart-sample-data'); ?></h1>
        <?php if (! $ready) : ?><div class="notice notice-error"><p><?php esc_html_e('Activate PublishPress Cart or PublishPress Cart Pro first.', 'publishpress-cart-sample-data'); ?></p></div>
        <?php elseif ($this->count_records()) : ?><p><?php esc_html_e('Sample data exists. Removal deletes only records generated by this plugin.', 'publishpress-cart-sample-data'); ?></p><form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>"><input type="hidden" name="action" value="ppcart_sample_data_remove" /><?php wp_nonce_field('ppcart_sample_data_remove'); submit_button(__('Remove Sample Data', 'publishpress-cart-sample-data'), 'delete', 'submit', false); ?></form>
        <?php else : ?><p><?php esc_html_e('Creates six products, 180 orders across the past year, 36 subscriptions, categories, and tags. Cart Pro also gets a global coupon, collection, offer path, and upgrade path. The included tax CSV is available for manual import. No payment gateway, email, webhook, or integration is contacted.', 'publishpress-cart-sample-data'); ?></p><form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>"><input type="hidden" name="action" value="ppcart_sample_data_generate" /><?php wp_nonce_field('ppcart_sample_data_generate'); submit_button(__('Generate Sample Data', 'publishpress-cart-sample-data'), 'primary', 'submit', false); ?></form><?php endif; ?></div><?php
    }

    public function generate()
    {
        $this->authorize('ppcart_sample_data_generate');
        if (! $this->cart_is_available()) { wp_die(esc_html__('Activate PublishPress Cart or PublishPress Cart Pro first.', 'publishpress-cart-sample-data')); }
        if ($this->count_records()) { wp_die(esc_html__('Generated records already exist. Remove them before generating again.', 'publishpress-cart-sample-data')); }
        $products = $this->products(); $now = current_time('timestamp', true); $orders = array();
        if (! $products) { wp_die(esc_html__('Could not create products. Check the Cart post type and try again.', 'publishpress-cart-sample-data')); }
        for ($i = 0; $i < 180; $i++) { $orders[] = $this->order($products[$i % count($products)], $i, $now - DAY_IN_SECONDS * (364 - (($i * 17) % 365))); }
        $this->subscriptions($orders); $this->pro_records($products, $orders);
        do_action('ppcart_sample_data_generate_affiliate_payments', $orders);
        $this->redirect();
    }

    public function remove()
    {
        $this->authorize('ppcart_sample_data_remove');
        foreach (get_posts(array('post_type' => $this->record_types(), 'post_status' => 'any', 'posts_per_page' => -1, 'fields' => 'ids', 'meta_key' => self::META_KEY, 'meta_value' => '1')) as $id) { wp_delete_post($id, true); }
        do_action('ppcart_sample_data_remove_affiliate_payments'); $this->redirect();
    }

    private function products()
    {
        $products = array();
        foreach (array(array('Creator Course', 149), array('Monthly Membership', 29), array('Coaching Package', 499), array('Template Bundle', 39), array('Live Workshop', 79), array('Free Starter Guide', 0)) as $index => $data) {
            $id = wp_insert_post(array('post_title' => $data[0], 'post_type' => 'ppcart_product', 'post_status' => 'publish'), true);
            if (is_wp_error($id)) { continue; }
            $plan = array('option_id' => sanitize_title($data[0]) . '-standard', 'option_name' => $data[0], 'product_type' => $index === 1 ? 'recurring' : ($data[1] ? '' : 'free'), 'price' => (string) $data[1], 'interval' => 'month', 'frequency' => 1, 'installments' => 0);
            update_post_meta($id, '_ppcart_pay_options', array($plan)); update_post_meta($id, self::META_KEY, '1'); $products[] = array($id, $data[0], $data[1], $plan);
            wp_set_object_terms($id, $index % 2 ? 'Courses' : 'Digital Downloads', 'ppcart_product_cat', false);
            wp_set_object_terms($id, $index % 2 ? 'membership' : 'templates', 'ppcart_product_tag', false);
        }
        return $products;
    }

    private function order($product, $index, $timestamp)
    {
        $states = array('paid', 'paid', 'paid', 'refunded', 'failed', 'pending-payment'); $state = $states[$index % count($states)];
        $names = array(array('Alex','Morgan'), array('Olivia','Martin'), array('Noah','Williams'), array('Emma','Garcia'), array('Liam','Taylor'), array('Sophia','Brown')); $name = $names[$index % count($names)];
        $date = gmdate('Y-m-d H:i:s', $timestamp);
        $id = wp_insert_post(array('post_title' => $name[0] . ' ' . $name[1], 'post_type' => 'ppcart_order', 'post_status' => 'ppcart_' . ($state === 'pending-payment' ? 'pending' : $state), 'post_date_gmt' => $date, 'post_date' => get_date_from_gmt($date)), true);
        if (is_wp_error($id)) { return 0; }
        $meta = array('status' => $state, 'payment_status' => $state, 'product_id' => $product[0], 'product_name' => $product[1], 'amount' => $product[2], 'invoice_total' => $product[2], 'invoice_subtotal' => $product[2], 'currency' => 'USD', 'first_name' => $name[0], 'last_name' => $name[1], 'customer_name' => $name[0] . ' ' . $name[1], 'email' => strtolower($name[0] . '.' . $name[1] . ($index + 1) . '@example.test'), 'plan' => $product[3], 'coupon_id' => $index % 10 === 0 ? 'WELCOME10' : '');
        foreach ($meta as $key => $value) { if ('' !== $value) { update_post_meta($id, '_ppcart_' . $key, $value); } } update_post_meta($id, self::META_KEY, '1'); return $id;
    }

    private function subscriptions($orders)
    {
        foreach (array_slice(array_filter($orders), 0, 36) as $index => $order_id) {
            $status = array('active', 'paused', 'canceled', 'completed')[$index % 4];
            $id = wp_insert_post(array('post_title' => get_the_title($order_id), 'post_type' => 'ppcart_subscription', 'post_status' => 'ppcart_' . $status), true);
            if (is_wp_error($id)) { continue; }
            foreach (array('customer_name','first_name','last_name','email','product_id','product_name','currency','amount') as $key) { $value = get_post_meta($order_id, '_ppcart_' . $key, true); if ('' !== $value) { update_post_meta($id, '_ppcart_' . $key, $value); } }
            update_post_meta($id, '_ppcart_status', $status); update_post_meta($id, '_ppcart_sub_status', $status); update_post_meta($id, '_ppcart_first_order', $order_id); update_post_meta($id, self::META_KEY, '1');
        }
    }

    private function pro_records($products, $orders)
    {
        if (! defined('PPCART_PRO_VERSION')) { return; }
        $coupon = $this->pro_post('ppcart_global_coupon', 'WELCOME20'); if ($coupon) { update_post_meta($coupon, '_ppcart_global_coupon_percent', '20'); }
        $collection = $this->pro_post('ppcart_collection', 'Creator Launch Bundle'); if ($collection) { update_post_meta($collection, '_ppcart_product_options', array($products[0][0], $products[3][0])); update_post_meta($collection, '_ppcart_pay_options', array($products[0][3])); }
        $offer = $this->pro_post('ppcart_us_path', 'VIP Coaching Offer'); if ($offer) { update_post_meta($products[0][0], '_ppcart_upsell_path', $offer); }
        $this->pro_post('ppcart_upgrade_path', 'Membership Upgrade');
        do_action('ppcart_sample_data_generate_affiliates', $orders, $products);
    }

    private function pro_post($type, $title)
    {
        if (! post_type_exists($type)) { return 0; }
        $id = wp_insert_post(array('post_title' => $title, 'post_type' => $type, 'post_status' => 'publish'), true);
        if (is_wp_error($id)) { return 0; } update_post_meta($id, self::META_KEY, '1'); return $id;
    }

    private function cart_is_available() { return post_type_exists('ppcart_product') && (defined('PPCART_VERSION') || defined('PPCART_PRO_VERSION')); }
    private function record_types() { return array('ppcart_product', 'ppcart_order', 'ppcart_subscription', 'ppcart_global_coupon', 'ppcart_collection', 'ppcart_us_path', 'ppcart_upgrade_path'); }
    private function count_records() { $q = new WP_Query(array('post_type' => $this->record_types(), 'post_status' => 'any', 'posts_per_page' => 1, 'meta_key' => self::META_KEY, 'meta_value' => '1')); return (int) $q->found_posts; }
    private function authorize($action) { if (! current_user_can('manage_options')) { wp_die(esc_html__('You are not allowed to manage sample data.', 'publishpress-cart-sample-data')); } check_admin_referer($action); }
    private function redirect() { wp_safe_redirect(admin_url('admin.php?page=ppcart-sample-data')); exit; }
}
new PPCart_Sample_Data_Plugin();

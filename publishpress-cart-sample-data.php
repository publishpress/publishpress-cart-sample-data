defined('ABSPATH') || exit;

final class PPCart_Sample_Data_Plugin
{
    const META_KEY = '_ppcart_sample_data';

    public function __construct()
    {
        add_action('admin_menu', array($this, 'register_page'));
        add_action('admin_post_ppcart_sample_data_generate', array($this, 'generate'));
        add_action('admin_post_ppcart_sample_data_remove', array($this, 'remove'));
    }

    public function register_page()
    {
        add_management_page(__('Cart Sample Data', 'publishpress-cart-sample-data'), __('Cart Sample Data', 'publishpress-cart-sample-data'), 'manage_options', 'ppcart-sample-data', array($this, 'render'));
    }

    public function render()
    {
        $ready = $this->cart_is_available();
        ?>
        <div class="wrap"><h1><?php esc_html_e('PublishPress Cart Sample Data', 'publishpress-cart-sample-data'); ?></h1>
        <?php if (! $ready) : ?><div class="notice notice-error"><p><?php esc_html_e('Activate PublishPress Cart or PublishPress Cart Pro first.', 'publishpress-cart-sample-data'); ?></p></div>
        <?php elseif (! $this->safe_environment()) : ?><div class="notice notice-warning"><p><?php esc_html_e('Sample data is limited to local, development, and staging sites. To explicitly allow this approved test site, add define( \'PPCART_SAMPLE_DATA_ALLOW\', true ); to wp-config.php.', 'publishpress-cart-sample-data'); ?></p></div>
        <?php elseif ($this->count_records()) : ?><p><?php esc_html_e('Sample data exists. Removal deletes only records generated by this plugin.', 'publishpress-cart-sample-data'); ?></p><form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>"><input type="hidden" name="action" value="ppcart_sample_data_remove" /><?php wp_nonce_field('ppcart_sample_data_remove'); submit_button(__('Remove Sample Data', 'publishpress-cart-sample-data'), 'delete', 'submit', false); ?></form>
        <?php else : ?><p><?php esc_html_e('Creates 12 months of fake products, customer orders, subscriptions, payment plans, coupon usage, and Pro affiliate sample records. No payment gateway, email, webhook, or integration is contacted.', 'publishpress-cart-sample-data'); ?></p><form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>"><input type="hidden" name="action" value="ppcart_sample_data_generate" /><?php wp_nonce_field('ppcart_sample_data_generate'); submit_button(__('Generate Sample Data', 'publishpress-cart-sample-data'), 'primary', 'submit', false); ?></form><?php endif; ?></div><?php
    }

    public function generate()
    {
        $this->authorize('ppcart_sample_data_generate');
        if (! $this->cart_is_available() || ! $this->safe_environment()) { wp_die(esc_html__('Sample data is unavailable on this site.', 'publishpress-cart-sample-data')); }
        $products = $this->products(); $now = current_time('timestamp', true);
        for ($i = 0; $i < 180; $i++) { $this->order($products[$i % count($products)], $i, $now - DAY_IN_SECONDS * (364 - (($i * 17) % 365))); }
        do_action('ppcart_sample_data_generate_affiliate_payments');
        $this->redirect();
    }

    public function remove()
    {
        $this->authorize('ppcart_sample_data_remove');
        foreach (get_posts(array('post_type' => array('ppcart_product', 'ppcart_order', 'ppcart_subscription'), 'post_status' => 'any', 'posts_per_page' => -1, 'fields' => 'ids', 'meta_key' => self::META_KEY, 'meta_value' => '1')) as $id) { wp_delete_post($id, true); }
        do_action('ppcart_sample_data_remove_affiliate_payments'); $this->redirect();
    }

    private function products()
    {
        $products = array();
        foreach (array(array('Creator Course', 149), array('Monthly Membership', 29), array('Coaching Package', 499), array('Template Bundle', 39), array('Live Workshop', 79), array('Free Starter Guide', 0)) as $index => $data) {
            $id = wp_insert_post(array('post_title' => $data[0] . ' (Sample)', 'post_type' => 'ppcart_product', 'post_status' => 'publish'), true);
            if (is_wp_error($id)) { continue; }
            $plan = array('option_id' => 'sample-' . $index, 'option_name' => $data[0], 'product_type' => $index === 1 ? 'recurring' : ($data[1] ? 'one-time' : 'free'), 'price' => (string) $data[1], 'interval' => 'month', 'frequency' => 1, 'installments' => 0);
            update_post_meta($id, '_ppcart_pay_options', array($plan)); update_post_meta($id, self::META_KEY, '1'); $products[] = array($id, $data[0], $data[1], $plan);
        }
        return $products;
    }

    private function order($product, $index, $timestamp)
    {
        $states = array('paid', 'paid', 'paid', 'refunded', 'failed', 'pending-payment'); $state = $states[$index % count($states)];
        $id = wp_insert_post(array('post_title' => 'Sample Customer ' . ($index % 36 + 1), 'post_type' => 'ppcart_order', 'post_status' => 'ppcart_' . ($state === 'pending-payment' ? 'pending' : $state), 'post_date_gmt' => gmdate('Y-m-d H:i:s', $timestamp)), true);
        if (is_wp_error($id)) { return; }
        $meta = array('status' => $state, 'payment_status' => $state, 'product_id' => $product[0], 'product_name' => $product[1], 'amount' => $product[2], 'invoice_total' => $product[2], 'currency' => 'USD', 'customer_name' => 'Sample Customer ' . ($index % 36 + 1), 'email' => 'sample-' . ($index % 36 + 1) . '@example.test', 'plan' => $product[3], 'coupon_id' => $index % 10 === 0 ? 'SAMPLE10' : '');
        foreach ($meta as $key => $value) { if ('' !== $value) { update_post_meta($id, '_ppcart_' . $key, $value); } } update_post_meta($id, self::META_KEY, '1');
    }

    private function cart_is_available() { return post_type_exists('ppcart_product') && (defined('PPCART_VERSION') || defined('PPCART_PRO_VERSION')); }
    private function safe_environment()
    {
        if (defined('PPCART_SAMPLE_DATA_ALLOW') && PPCART_SAMPLE_DATA_ALLOW) { return true; }
        return in_array(wp_get_environment_type(), array('local', 'development', 'staging'), true);
    }
    private function count_records() { $q = new WP_Query(array('post_type' => array('ppcart_product', 'ppcart_order', 'ppcart_subscription'), 'post_status' => 'any', 'posts_per_page' => 1, 'meta_key' => self::META_KEY, 'meta_value' => '1')); return (int) $q->found_posts; }
    private function authorize($action) { if (! current_user_can('manage_options')) { wp_die(esc_html__('You are not allowed to manage sample data.', 'publishpress-cart-sample-data')); } check_admin_referer($action); }
    private function redirect() { wp_safe_redirect(admin_url('tools.php?page=ppcart-sample-data')); exit; }
}
new PPCart_Sample_Data_Plugin();

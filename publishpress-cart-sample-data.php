final class PPCart_Sample_Data_Plugin
{
    const META_KEY = '_ppcart_sample_data';

    public function __construct()
    {
        add_action('admin_menu', array($this, 'register_page'));
        add_action('admin_post_ppcart_sample_data_generate', array($this, 'generate'));
        add_action('admin_post_ppcart_sample_data_remove', array($this, 'remove'));
    }

    public function register_page()
    {
        $parent = $this->is_studiocart() ? 'studiocart' : 'ppcart';
        add_submenu_page($parent, __('Sample Data', 'publishpress-cart-sample-data'), __('Sample Data', 'publishpress-cart-sample-data'), 'manage_options', 'ppcart-sample-data', array($this, 'render'));
    }

    public function render()
    {
        $ready = $this->cart_is_available();
        ?>
        <div class="wrap"><h1><?php esc_html_e('Cart Sample Data', 'publishpress-cart-sample-data'); ?></h1>
        <?php if (! $ready) : ?><div class="notice notice-error"><p><?php esc_html_e('Activate PublishPress Cart or Studiocart first.', 'publishpress-cart-sample-data'); ?></p></div>
        <?php elseif ($this->count_records()) : ?><p><?php esc_html_e('Sample data exists. Removal deletes only records generated by this plugin.', 'publishpress-cart-sample-data'); ?></p><form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>"><input type="hidden" name="action" value="ppcart_sample_data_remove" /><?php wp_nonce_field('ppcart_sample_data_remove'); submit_button(__('Remove Sample Data', 'publishpress-cart-sample-data'), 'delete', 'submit', false); ?></form>
        <?php else : ?><p><?php echo esc_html(sprintf(__('Creates six products, 180 orders across the past year, 36 subscriptions, categories, and tags for %s. Premium catalog records are added when their post types are available. The included PublishPress Cart tax CSV is for manual import. No payment gateway, email, webhook, or integration is contacted.', 'publishpress-cart-sample-data'), $this->is_studiocart() ? 'Studiocart' : 'PublishPress Cart')); ?></p><form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>"><input type="hidden" name="action" value="ppcart_sample_data_generate" /><?php wp_nonce_field('ppcart_sample_data_generate'); submit_button(__('Generate Sample Data', 'publishpress-cart-sample-data'), 'primary', 'submit', false); ?></form><?php endif; ?></div><?php
    }

    public function generate()
    {
        $this->authorize('ppcart_sample_data_generate');
        if (! $this->cart_is_available()) { wp_die(esc_html__('Activate PublishPress Cart or Studiocart first.', 'publishpress-cart-sample-data')); }
        if ($this->count_records()) { wp_die(esc_html__('Generated records already exist. Remove them before generating again.', 'publishpress-cart-sample-data')); }
        $products = $this->products(); $now = current_time('timestamp', true); $orders = array();
        if (count($products) !== 6) {
            foreach ($products as $product) { wp_delete_post($product[0], true); }
            wp_die(esc_html__('Could not create all products. Check the cart post type and try again.', 'publishpress-cart-sample-data'));
        }
        for ($i = 0; $i < 180; $i++) { $orders[] = $this->order($i % 5 === 0 ? $products[1] : $products[$i % count($products)], $i, $now - DAY_IN_SECONDS * (364 - (($i * 17) % 365))); }
        $this->subscriptions($orders, $products[1][0]); $this->pro_records($products, $orders);
        if (! $this->is_studiocart()) { do_action('ppcart_sample_data_generate_affiliate_payments', $orders); }
        $this->redirect();
    }

    public function remove()
    {
        $this->authorize('ppcart_sample_data_remove');
        foreach (get_posts(array('post_type' => $this->record_types(), 'post_status' => 'any', 'posts_per_page' => -1, 'fields' => 'ids', 'meta_key' => self::META_KEY, 'meta_value' => '1')) as $id) {
            if (get_post_type($id) === $this->type('order')) { $this->remove_download_access($id); }
            wp_delete_post($id, true);
        }
        if (! $this->is_studiocart()) { do_action('ppcart_sample_data_remove_affiliate_payments'); }
        $this->redirect();
    }

    private function products()
    {
        $products = array();
        foreach (array(array('Creator Course', 149), array('Monthly Membership', 29), array('Coaching Package', 499), array('Template Bundle', 39), array('Live Workshop', 79), array('Free Starter Guide', 0)) as $index => $data) {
            $id = wp_insert_post(array('post_title' => $data[0], 'post_type' => $this->type('product'), 'post_status' => 'publish'), true);
            if (is_wp_error($id)) { continue; }
            $plan = array('option_id' => sanitize_title($data[0]) . '-standard', 'option_name' => $data[0], 'product_type' => $index === 1 ? 'recurring' : ($data[1] ? '' : 'free'), 'price' => (string) $data[1], 'interval' => 'month', 'frequency' => 1, 'installments' => 0);
            update_post_meta($id, $this->meta('pay_options'), array($plan)); update_post_meta($id, self::META_KEY, '1'); $products[] = array($id, $data[0], $data[1], $plan);
            $this->product_download($id, $index);
            wp_set_object_terms($id, $index % 2 ? 'Courses' : 'Digital Downloads', $this->type('product_cat'), false);
            wp_set_object_terms($id, $index % 2 ? 'membership' : 'templates', $this->type('product_tag'), false);
        }
        return $products;
    }

    private function order($product, $index, $timestamp)
    {
        $states = array('paid', 'paid', 'paid', 'refunded', 'failed', 'pending-payment'); $state = $product[3]['product_type'] === 'recurring' ? 'paid' : $states[(int) floor($index / 6) % count($states)];
        $names = array(array('Alex','Morgan'), array('Olivia','Martin'), array('Noah','Williams'), array('Emma','Garcia'), array('Liam','Taylor'), array('Sophia','Brown')); $name = $names[$index % count($names)];
        $date = gmdate('Y-m-d H:i:s', $timestamp);
        $id = wp_insert_post(array('post_title' => $name[0] . ' ' . $name[1], 'post_type' => $this->type('order'), 'post_status' => $this->status($state), 'post_date_gmt' => $date, 'post_date' => get_date_from_gmt($date)), true);
        if (is_wp_error($id)) { return 0; }
        $plan = $product[3];
        if ($this->is_studiocart()) {
            $plan = (object) array('type' => $plan['product_type'] ?: 'one-time', 'name' => $plan['option_name'], 'option_id' => $plan['option_id'], 'price' => $plan['price'], 'initial_payment' => (float) $plan['price'], 'interval' => $plan['interval'], 'frequency' => $plan['frequency'], 'installments' => $plan['installments'], 'stripe_id' => '');
        }
        $meta = array('status' => $state, 'payment_status' => $state, 'product_id' => $product[0], 'product_name' => $product[1], 'item_name' => $product[1], 'option_id' => $product[3]['option_id'], 'amount' => $product[2], 'invoice_total' => $product[2], 'invoice_subtotal' => $product[2], 'main_offer_amt' => $product[2], 'currency' => 'USD', 'first_name' => $name[0], 'last_name' => $name[1], 'customer_name' => $name[0] . ' ' . $name[1], 'email' => strtolower($name[0] . '.' . $name[1] . ($index + 1) . '@example.test'), 'plan' => $plan, 'coupon_id' => ! $this->is_studiocart() && $index % 10 === 0 ? 'WELCOME10' : '');
        foreach ($meta as $key => $value) { if ('' !== $value) { update_post_meta($id, $this->meta($key), $value); } }
        update_post_meta($id, self::META_KEY, '1');
        if ($state === 'paid') { $this->attach_download_access($id, $product[0]); }
        return $id;
    }

    private function product_download($product_id, $index)
    {
        $files = array(
            0 => array('creator-workbook', 'Creator Course Workbook', 'creator-course-workbook.html'),
            3 => array('content-calendar', 'Content Calendar', 'content-calendar.csv'),
            4 => array('workshop-checklist', 'Live Workshop Checklist', 'live-workshop-checklist.txt'),
            5 => array('starter-guide', 'Starter Guide', 'starter-guide.html'),
        );
        if (! isset($files[$index])) { return; }
        $file = $files[$index];
        update_post_meta($product_id, $this->meta('files'), array(array(
            'file_id' => $file[0],
            'file_name' => $file[1],
            'file_url' => plugins_url('sample-data/downloads/' . $file[2], __FILE__),
            'file_redirect' => '1',
            'file_plan' => array(),
            'file_limit' => '',
        )));
    }

    private function download_table()
    {
        global $wpdb;
        static $checked = false;
        static $available = '';
        if ($checked) { return $available; }
        $checked = true;
        $table = $this->is_studiocart() ? $wpdb->prefix . 'ncs_downloads' : (class_exists('PPCart_Files') && method_exists('PPCart_Files', 'live_table') ? PPCart_Files::live_table() : $wpdb->prefix . 'ppcart_downloads');
        if (! $table) { return ''; }
        $available = $wpdb->get_var($wpdb->prepare('SHOW TABLES LIKE %s', $wpdb->esc_like($table))) === $table ? $table : '';
        return $available;
    }

    private function attach_download_access($order_id, $product_id)
    {
        global $wpdb;
        $table = $this->download_table();
        $files = get_post_meta($product_id, $this->meta('files'), true);
        if (! $table || ! is_array($files)) { return; }
        foreach ($files as $file) {
            $wpdb->insert($table, array(
                'file_id' => $file['file_id'],
                'order_id' => $order_id,
                'order_key' => wp_generate_password(20, false, false),
                'product_id' => $product_id,
                'access_granted' => get_post($order_id)->post_date_gmt,
                'download_expires' => null,
                'downloads_remaining' => 'unlimited',
            ), array('%s', '%d', '%s', '%d', '%s', '%s', '%s'));
        }
    }

    private function remove_download_access($order_id)
    {
        global $wpdb;
        $table = $this->download_table();
        if ($table) { $wpdb->delete($table, array('order_id' => $order_id), array('%d')); }
    }

    private function subscriptions($orders, $recurring_product_id)
    {
        $recurring_orders = array_values(array_filter($orders, function ($order_id) use ($recurring_product_id) {
            return $order_id && (int) get_post_meta($order_id, $this->meta('product_id'), true) === $recurring_product_id;
        }));
        foreach (array_slice($recurring_orders, 0, 36) as $index => $order_id) {
            $status = array('active', 'paused', 'canceled', 'completed')[$index % 4];
            $order = get_post($order_id);
            $id = wp_insert_post(array('post_title' => get_the_title($order_id), 'post_type' => $this->type('subscription'), 'post_status' => $this->status($status), 'post_date_gmt' => $order->post_date_gmt, 'post_date' => $order->post_date), true);
            if (is_wp_error($id)) { continue; }
            foreach (array('customer_name','first_name','last_name','email','product_id','product_name','currency','amount') as $key) { $value = get_post_meta($order_id, $this->meta($key), true); if ('' !== $value) { update_post_meta($id, $this->meta($key), $value); } }
            update_post_meta($id, $this->meta('subscription_id'), wp_generate_uuid4());
            update_post_meta($id, $this->meta('sub_amount'), get_post_meta($order_id, $this->meta('amount'), true));
            update_post_meta($id, $this->meta('sub_item_name'), 'Monthly Membership');
            update_post_meta($id, $this->meta('sub_interval'), 'month');
            update_post_meta($id, $this->meta('sub_frequency'), 1);
            update_post_meta($id, $this->meta('option_id'), get_post_meta($order_id, $this->meta('option_id'), true));
            update_post_meta($id, $this->meta('status'), $status); update_post_meta($id, $this->meta('sub_status'), $status); update_post_meta($id, $this->meta('first_order'), $order_id); update_post_meta($id, self::META_KEY, '1');
            update_post_meta($order_id, $this->meta('subscription_id'), $id);
        }
    }

    private function pro_records($products, $orders)
    {
        if ($this->is_studiocart()) {
            $collection = $this->pro_post($this->type('collection'), 'Creator Launch Bundle');
            if ($collection) { update_post_meta($collection, $this->meta('product_options'), array($products[0][0], $products[3][0])); update_post_meta($collection, $this->meta('pay_options'), array($products[0][3])); }
            $offer = $this->pro_post($this->type('us_path'), 'VIP Coaching Offer');
            if ($offer) { update_post_meta($products[0][0], $this->meta('upsell_path'), $offer); }
            return;
        }
        if (! defined('PPCART_PRO_VERSION')) { return; }
        $coupon = $this->pro_post('ppcart_global_coupon', 'WELCOME20'); if ($coupon) { update_post_meta($coupon, '_ppcart_global_coupon_percent', '20'); }
        $collection = $this->pro_post('ppcart_collection', 'Creator Launch Bundle'); if ($collection) { update_post_meta($collection, '_ppcart_product_options', array($products[0][0], $products[3][0])); update_post_meta($collection, '_ppcart_pay_options', array($products[0][3])); }
        $offer = $this->pro_post('ppcart_us_path', 'VIP Coaching Offer'); if ($offer) { update_post_meta($products[0][0], '_ppcart_upsell_path', $offer); }
        $this->pro_post('ppcart_upgrade_path', 'Membership Upgrade');
        do_action('ppcart_sample_data_generate_affiliates', $orders, $products);
    }

    private function pro_post($type, $title)
    {
        if (! post_type_exists($type)) { return 0; }
        $id = wp_insert_post(array('post_title' => $title, 'post_type' => $type, 'post_status' => 'publish'), true);
        if (is_wp_error($id)) { return 0; } update_post_meta($id, self::META_KEY, '1'); return $id;
    }

    private function is_studiocart() { return post_type_exists('sc_product') && defined('NCS_CART_VERSION') && ! post_type_exists('ppcart_product'); }
    private function cart_is_available() { return $this->is_studiocart() || (post_type_exists('ppcart_product') && (defined('PPCART_VERSION') || defined('PPCART_PRO_VERSION'))); }
    private function type($name) { return ($this->is_studiocart() ? 'sc_' : 'ppcart_') . $name; }
    private function meta($name) { return '_' . $this->type($name); }
    private function status($name) { return $this->is_studiocart() ? $name : 'ppcart_' . ($name === 'pending-payment' ? 'pending' : $name); }
    private function record_types() { $names = $this->is_studiocart() ? array('product', 'order', 'subscription', 'collection', 'us_path') : array('product', 'order', 'subscription', 'global_coupon', 'collection', 'us_path', 'upgrade_path'); return array_map(array($this, 'type'), $names); }
    private function count_records() { $q = new WP_Query(array('post_type' => $this->record_types(), 'post_status' => 'any', 'posts_per_page' => 1, 'meta_key' => self::META_KEY, 'meta_value' => '1')); return (int) $q->found_posts; }
    private function authorize($action) { if (! current_user_can('manage_options')) { wp_die(esc_html__('You are not allowed to manage sample data.', 'publishpress-cart-sample-data')); } check_admin_referer($action); }
    private function redirect() { wp_safe_redirect(admin_url('admin.php?page=ppcart-sample-data')); exit; }
}
new PPCart_Sample_Data_Plugin();
